let current = 'en';

export const setLang = code => { current = STRINGS[code] ? code : 'en'; };
export const getLang = () => current;
export const locale = () => LOCALES[current] || 'en';

/* Picks the best match for the phone's language on first run. */
export function detectLang() {
  for (const tag of navigator.languages || [navigator.language || 'en']) {
    const base = String(tag).toLowerCase().split('-')[0];
    if (STRINGS[base]) return base;
  }
  return 'en';
}

export function t(key, vars) {
  let str = STRINGS[current]?.[key] ?? STRINGS.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) str = str.replaceAll(`{${k}}`, v);
  }
  return str;
}

/* English needs an "s"; Vietnamese does not inflect, so it resolves to nothing. */
export const plural = n => (current === 'en' && n !== 1 ? 's' : '');
